                    const filtered = localExercises.filter(e => {
                        const diff = parseInt(e.difficulty || 1, 10);
                        if (activeLevelFilter !== 'all' && String(diff) !== String(activeLevelFilter)) {
                            return false;
                        }
                        if (!q) return true;
                        const diffText = (diffLabels[diff] || '').toLowerCase();
                        return (e.name && e.name.toLowerCase().includes(q)) ||
                               (e.muscle_group && e.muscle_group.toLowerCase().includes(q)) ||
                               (e.category && e.category.toLowerCase().includes(q)) ||
                               diffText.includes(q);
                    });

