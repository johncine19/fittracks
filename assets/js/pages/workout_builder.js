    // 5. Publish Prompt
    function promptPublish() {
        const isLive = window.WORKOUT_BUILDER_CONFIG && window.WORKOUT_BUILDER_CONFIG.isLivePlan;
        const cfgToday = window.WORKOUT_BUILDER_CONFIG?.today || todayStr;
        const curStart = (defaultStart && defaultStart >= cfgToday) ? defaultStart : cfgToday;
        const memEnd = window.WORKOUT_BUILDER_CONFIG?.membershipEndDate || membershipEndDate || defaultEnd;
        const planName = window.WORKOUT_BUILDER_CONFIG?.membershipPlanName || membershipPlanName;
        Swal.fire({
            title: isLive ? 'Update Workout Schedule' : 'Publish Workout Plan',
            width: 'min(94vw, 520px)',
            html: `
                <div style="text-align: left; display: flex; flex-direction: column; gap: 14px;">
                    <p style="margin:0; color:var(--ink); font-size: 14px;">
                        ${isLive ? 'This will update the active schedule dates for this live routine.' : `This will activate the training plan and notify <strong>${memberName}</strong>.`}
                    </p>
                    ${!hasMembership ? `
                    <div style="background-color: rgba(255, 193, 7, 0.1); border-left: 4px solid var(--orange); padding: 10px; border-radius: 6px;">
                        <p style="margin: 0; font-size: 13px; color: var(--orange);">
                            <strong>Notice:</strong> This member does not currently hold an active membership. This plan will serve as a 7-day trial.
                        </p>
                    </div>
                    ` : ''}
                    <div style="display:flex; gap:10px;">
                        <label style="display:block; flex:1; color: var(--muted); font-size: 13px;">Start Date
                            <input type="date" id="swal-start" class="form-control" style="width:100%; margin-top:5px;" value="${curStart}" min="${cfgToday}" ${!hasMembership ? 'readonly' : ''}>
                        </label>
                        <label style="display:block; flex:1; color: var(--muted); font-size: 13px;">End Date
                            <input type="date" id="swal-end" class="form-control" style="width:100%; margin-top:5px;" value="${defaultEnd}" min="${curStart}" ${hasMembership && memEnd ? `max="${memEnd}"` : ''} ${!hasMembership ? 'readonly' : ''}>
                        </label>
                    </div>
                </div>
            `,
            showCancelButton: true,
            confirmButtonColor: 'var(--lime-dark, #84cc16)',
            cancelButtonColor: '#6c757d',
            background: 'var(--bg)',
            color: 'var(--ink)',
            confirmButtonText: isLive ? 'Save Schedule' : 'Yes, Publish Routine',
            didOpen: () => {
                const sEl = document.getElementById('swal-start');
                const eEl = document.getElementById('swal-end');
                if (sEl && eEl) {
                    sEl.addEventListener('change', () => {
                        eEl.min = sEl.value;
                        if (eEl.value && eEl.value < sEl.value) {
                            eEl.value = sEl.value;
                        }
                    });
                }
            },
            preConfirm: () => {
                const start = document.getElementById('swal-start').value;
                const end = document.getElementById('swal-end').value;
                if (!start || !end) {
                    Swal.showValidationMessage('Please select both start and end dates');
                    return false;
                }
                if (start < cfgToday) {
                    Swal.showValidationMessage('Start date cannot be in the past. Please select today or a future date.');
                    return false;
                }
                if (end < start) {
                    Swal.showValidationMessage('End date cannot precede start date');
                    return false;
                }
                if (hasMembership && memEnd && end > memEnd) {
                    Swal.showValidationMessage(`End date cannot exceed member's membership expiration date (${memEnd})`);
                    return false;
                }
                return { start, end };
            }
        }).then((result) => {
            if (result.isConfirmed) {
                Swal.showLoading();
                const form = document.getElementById('publishForm');
                
                let startInput = document.createElement('input');
                startInput.type = 'hidden';
                startInput.name = 'start_date';
                startInput.value = result.value.start;
                form.appendChild(startInput);

                let endInput = document.createElement('input');
                endInput.type = 'hidden';
                endInput.name = 'end_date';
                endInput.value = result.value.end;
                form.appendChild(endInput);
                
                form.submit();
            }
        });
    }

