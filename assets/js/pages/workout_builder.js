    function enhanceAutoGenerateDropdowns(popup) {
        const selects = popup.querySelectorAll('.swal2-html-container select');
        selects.forEach((select) => {
            const wrapper = document.createElement('div');
            wrapper.className = 'wb-modal-select-wrap';
            select.parentNode.insertBefore(wrapper, select);
            wrapper.appendChild(select);
            select.classList.add('wb-modal-select-native');
            select.tabIndex = -1;
            select.setAttribute('aria-hidden', 'true');

            const trigger = document.createElement('button');
            trigger.type = 'button';
            trigger.className = 'wb-modal-select-trigger';
            trigger.setAttribute('aria-haspopup', 'listbox');
            trigger.setAttribute('aria-expanded', 'false');
            trigger.innerHTML = `<span class="wb-modal-select-value"></span><span class="wb-modal-select-chevron" aria-hidden="true">⌄</span>`;
            wrapper.appendChild(trigger);

            const menu = document.createElement('div');
            menu.className = 'wb-modal-select-menu';
            menu.setAttribute('role', 'listbox');
            Array.from(select.options).forEach((option) => {
                const item = document.createElement('button');
                item.type = 'button';
                item.className = 'wb-modal-select-option';
                item.textContent = option.textContent;
                item.dataset.value = option.value;
                item.setAttribute('role', 'option');
                item.setAttribute('aria-selected', option.selected ? 'true' : 'false');
                item.addEventListener('click', () => {
                    select.value = option.value;
                    trigger.querySelector('.wb-modal-select-value').textContent = option.textContent;
                    menu.querySelectorAll('.wb-modal-select-option').forEach((entry) => {
                        entry.setAttribute('aria-selected', entry.dataset.value === option.value ? 'true' : 'false');
                    });
                    select.dispatchEvent(new Event('change', { bubbles: true }));
                    wrapper.classList.remove('is-open', 'opens-up');
                    trigger.setAttribute('aria-expanded', 'false');
                });
                menu.appendChild(item);
            });
            wrapper.appendChild(menu);
            trigger.querySelector('.wb-modal-select-value').textContent = select.options[select.selectedIndex]?.textContent || '';

            trigger.addEventListener('click', () => {
                const shouldOpen = !wrapper.classList.contains('is-open');
                popup.querySelectorAll('.wb-modal-select-wrap.is-open').forEach((open) => {
                    open.classList.remove('is-open', 'opens-up');
                    open.querySelector('.wb-modal-select-trigger').setAttribute('aria-expanded', 'false');
                });
                if (!shouldOpen) return;
                const htmlContainer = popup.querySelector('.swal2-html-container');
                const availableBelow = htmlContainer.getBoundingClientRect().bottom - trigger.getBoundingClientRect().bottom;
                const availableAbove = trigger.getBoundingClientRect().top - htmlContainer.getBoundingClientRect().top;
                const opensUp = availableBelow < 180 && availableAbove > availableBelow;
                wrapper.classList.toggle('opens-up', opensUp);
                menu.style.maxHeight = `${Math.max(96, Math.min(180, (opensUp ? availableAbove : availableBelow) - 8))}px`;
                wrapper.classList.add('is-open');
                trigger.setAttribute('aria-expanded', 'true');
            });
        });
        popup.addEventListener('click', (event) => {
            if (event.target.closest('.wb-modal-select-wrap')) return;
            popup.querySelectorAll('.wb-modal-select-wrap.is-open').forEach((open) => {
                open.classList.remove('is-open', 'opens-up');
                open.querySelector('.wb-modal-select-trigger').setAttribute('aria-expanded', 'false');
            });
        });
    }

